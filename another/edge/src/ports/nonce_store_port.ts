/**
 * NonceStorePort — anti-replay леджер (§7.2 спецификации).
 *
 * КЛЮЧЕВОЕ АРХИТЕКТУРНОЕ РЕШЕНИЕ (правка #2 относительно исходного
 * черновика): реализация ДОЛЖНА быть строго консистентной. Черновик
 * предлагал Cloudflare Cache API (`caches.default`), который привязан к
 * конкретному дата-центру (PoP) и не гарантирует глобальной консистентности
 * — запрос, попавший в другой PoP в течение TTL, не увидит записанный nonce,
 * и replay-атака технически проходит. Здесь единственная реализация порта —
 * DurableObjectNonceStore (см. adapters/durable_object_nonce_store.ts),
 * который даёт строгую консистентность за счёт единого объекта-владельца.
 */
export interface NonceStorePort {
  /** Выдаёт новый одноразовый nonce с TTL (см. реализацию адаптера). */
  issueNonce(): Promise<string>;

  /**
   * Атомарно помечает nonce использованным. Возвращает false, если nonce
   * не существовал, истёк, либо уже был использован ранее (replay).
   */
  consumeNonce(nonce: string): Promise<boolean>;
}
