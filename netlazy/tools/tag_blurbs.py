def _age_ru(number):
    tail = number % 10
    hundred = number % 100
    if tail == 1 and hundred != 11:
        return f"{number} год"
    if tail in (2, 3, 4) and hundred not in (12, 13, 14):
        return f"{number} года"
    return f"{number} лет"


