def lang_blurb(name, i18n):
    learning = name.startswith("learning ")
    key = name[len("learning "):] if learning else name.split(" (", 1)[0]
    prep, acc, _en, pt0, zh0, ja0, ko0 = LANG[key]
    pt = pt0 if key == "ukrainian" else (_surface(i18n.get("pt")) or pt0)
    zh = _surface(i18n.get("zh")) or zh0
    ja = _surface(i18n.get("ja")) or ja0
    ko = _surface(i18n.get("ko")) or ko0
    if learning:
        return pack(
            f"learning {key}",
            f"учит {acc}",
            f"aprendendo {pt}",
            f"在學{zh}",
            f"{ja}を勉強してる",
            f"{_ko_object(ko)} 배우는 중",
        )
    return pack(
        f"speaks {key}",
        f"говорит на {prep}",
        f"fala {pt}",
        f"會說{zh}",
        f"{ja}が話せる",
        f"{_ko_means(ko)} 말함",
    )


def blurb(name, i18n, aliases):
    lower = {str(item).lower() for item in aliases}
    if name in RU_IN or "location" in lower:
        if name not in RU_IN:
            raise KeyError(f"no place phrase for {name}")
        return place_blurb(name, i18n)
    if name.endswith(" years old"):
        return age_blurb(name)
    if "(native/fluent)" in name or name.startswith("learning "):
        return lang_blurb(name, i18n)
    if name in WRITES:
        return writes_blurb(name)
    if name not in HAND:
        raise KeyError(f"no description for {name}")
    return HAND[name]
