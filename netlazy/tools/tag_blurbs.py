def _hangul_batchim(word):
    if not word:
        return None
    code = ord(word[-1])
    if 0xAC00 <= code <= 0xD7A3:
        return (code - 0xAC00) % 28
    return None


def _ko_object(word):
    batchim = _hangul_batchim(word)
    if batchim:
        return word + "을"
    return word + "를"


def _ko_means(word):
    batchim = _hangul_batchim(word)
    if batchim and batchim != 8:
        return word + "으로"
    return word + "로"


def _surface(text):
    text = str(text or "").strip()
    text = text.split("（", 1)[0].split("(", 1)[0].strip()
    for prefix in ("正在學習", "aprendendo "):
        if text.startswith(prefix):
            text = text[len(prefix):].strip()
    for suffix in ("学習中", "학습 중"):
        if text.endswith(suffix):
            text = text[: -len(suffix)].strip()
    return text


